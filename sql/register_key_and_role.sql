-- CNDE Assignment 5: attach a key from this PC to CLAUDE_AGENT and create a read-only role.
-- Paste into a Snowsight worksheet and Run All (as ACCOUNTADMIN). Safe to re-run.
-- <PUBLIC_KEY> = the public key body (no BEGIN/END lines). The filled-in copy lives in local/ (git-ignored).
USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS CLASS_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE CLASS_WH SET AUTO_SUSPEND = 60;
CREATE USER IF NOT EXISTS CLAUDE_AGENT TYPE = SERVICE DEFAULT_WAREHOUSE = CLASS_WH COMMENT = 'Claude agent, key-pair login only';
ALTER USER CLAUDE_AGENT SET RSA_PUBLIC_KEY_2 = '<PUBLIC_KEY>';
CREATE ROLE IF NOT EXISTS A5_APP_RO COMMENT = 'CNDE A5 MCP server: SELECT only';
GRANT ROLE A5_APP_RO TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE CLASS_WH TO ROLE A5_APP_RO;
EXECUTE IMMEDIATE $$
DECLARE
  dbs STRING DEFAULT '';
  c1 CURSOR FOR SELECT DATABASE_NAME FROM CLASSICMODELS.INFORMATION_SCHEMA.DATABASES
                WHERE DATABASE_NAME ILIKE '%SAKILA%' OR DATABASE_NAME ILIKE 'CLASSICMODELS%';
BEGIN
  FOR rec IN c1 DO
    LET db STRING := '"' || rec.DATABASE_NAME || '"';
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE ' || db || ' TO ROLE A5_APP_RO';
    EXECUTE IMMEDIATE 'GRANT USAGE ON ALL SCHEMAS IN DATABASE ' || db || ' TO ROLE A5_APP_RO';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN DATABASE ' || db || ' TO ROLE A5_APP_RO';
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL VIEWS IN DATABASE ' || db || ' TO ROLE A5_APP_RO';
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE TABLES IN DATABASE ' || db || ' TO ROLE A5_APP_RO';
    dbs := dbs || rec.DATABASE_NAME || ' ';
  END FOR;
  RETURN 'A5_APP_RO can now read: ' || dbs;
END;
$$;
GRANT ROLE A5_APP_RO TO USER CLAUDE_AGENT;
SHOW GRANTS TO ROLE A5_APP_RO;
